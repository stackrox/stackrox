func TestDeleteAutogeneratedRegistries(t *testing.T) {
	ctx := context.Background()

	iis := []*storage.ImageIntegration{
		{Id: "NoAutogen-GlobalPull", Autogenerated: false, Source: &storage.ImageIntegration_Source{Namespace: openshift.GlobalPullSecretNamespace, ImagePullSecretName: openshift.GlobalPullSecretName}},
		{Id: "NoAutogen-NoSource", Autogenerated: false, Source: nil},
		{Id: "NoAutogen-Source", Autogenerated: false, Source: &storage.ImageIntegration_Source{}},
		{Id: "Autogen-GlobalPull", Autogenerated: true, Source: &storage.ImageIntegration_Source{Namespace: openshift.GlobalPullSecretNamespace, ImagePullSecretName: openshift.GlobalPullSecretName}},
		{Id: "Autogen-NoSource", Autogenerated: true, Source: nil},
		{Id: "Autogen-Source", Autogenerated: true, Source: &storage.ImageIntegration_Source{}},
	}

	testCases := []struct {
		name                     string
		expectedDeletes          []string
		autogenEnabled           bool
		sourcedAutogenEnabled    bool
		globalPullAutogenEnabled bool
	}{
		{
			"delete all autogen integrations when all autogen features disabled",
			[]string{"Autogen-GlobalPull", "Autogen-NoSource", "Autogen-Source"},
			false, false, false,
		},
		{
			"delete all autogen integrations when autogen disabled, sourced enabled, global pull disabled",
			[]string{"Autogen-GlobalPull", "Autogen-NoSource", "Autogen-Source"},
			false, true, false,
		},
		{
			"delete all autogen integrations when autogen disabled, sourced disabled, global pull enabled",
			[]string{"Autogen-GlobalPull", "Autogen-NoSource", "Autogen-Source"},
			false, false, true,
		},
		{
			"delete all autogen integrations when autogen disabled and all other autogen features enabled",
			[]string{"Autogen-GlobalPull", "Autogen-NoSource", "Autogen-Source"},
			false, true, true,
		},
		{
			"delete only sourced autogen integrations when autogen enabled and all other autogen features disabled",
			[]string{"Autogen-GlobalPull", "Autogen-Source"},
			true, false, false,
		},
		{
			"delete only non global pull sourced integrations when autogen enabled, sourced autogen disabled, and global pull enabled",
			[]string{"Autogen-Source"},
			true, false, true,
		},
		{
			"delete no integrations when autogen enabled, sourced autogen enabled, and global pull disabled",
			[]string{},
			true, true, false,
		},
		{
			"delete no integrations when all autogen features enabled",
			[]string{},
			true, true, true,
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			testutils.MustUpdateFeature(t, features.SourcedAutogeneratedIntegrations, tc.sourcedAutogenEnabled)
			t.Setenv(env.AutogeneratedRegistriesDisabled.EnvVar(), strconv.FormatBool(!tc.autogenEnabled))
			t.Setenv(env.AutogenerateGlobalPullSecRegistries.EnvVar(), strconv.FormatBool(tc.globalPullAutogenEnabled))

			ctrl := gomock.NewController(t)
			s := mockIIStore.NewMockStore(ctrl)
			if len(tc.expectedDeletes) > 0 {
				s.EXPECT().PruneMany(ctx, tc.expectedDeletes)
			}

			deleteAutogeneratedRegistries(ctx, s, iis)
		})
	}
}

func TestSetupScannerV4Integration(t *testing.T) {
	ctx := context.Background()

	defID := store.DefaultScannerV4Integration.GetId()

	iis := []*storage.ImageIntegration{
		{Id: "ID-Clairify", Type: scannerTypes.Clairify},
		{Id: "ID-Other-ScannerV4", Type: scannerTypes.ScannerV4},
		store.DefaultScannerV4Integration,
	}

	t.Run("do nothing if no scanner v4 integrations", func(t *testing.T) {
		testutils.MustUpdateFeature(t, features.ScannerV4, false)
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		setupScannerV4Integration(ctx, s, iis[:1])
	})

	t.Run("delete scanner v4 integrations if the feature is disabled", func(t *testing.T) {
		testutils.MustUpdateFeature(t, features.ScannerV4, false)
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		s.EXPECT().PruneMany(ctx, []string{"ID-Other-ScannerV4", defID})
		setupScannerV4Integration(ctx, s, iis)
	})

	t.Run("delete non default scanner v4 integrations and upsert default integration if feature enabled", func(t *testing.T) {
		testutils.MustUpdateFeature(t, features.ScannerV4, true)
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		s.EXPECT().Get(ctx, defID).Return(nil, false, nil)
		s.EXPECT().Upsert(ctx, store.DefaultScannerV4Integration).Return(nil)
		s.EXPECT().PruneMany(ctx, []string{"ID-Other-ScannerV4"})
		setupScannerV4Integration(ctx, s, iis)
	})

	t.Run("do not try upsert if error getting default integration", func(t *testing.T) {
		testutils.MustUpdateFeature(t, features.ScannerV4, true)
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		s.EXPECT().Get(ctx, defID).Return(nil, false, errors.New("fake"))

		if buildinfo.ReleaseBuild {
			s.EXPECT().PruneMany(ctx, []string{"ID-Other-ScannerV4"})
			setupScannerV4Integration(ctx, s, iis)
		} else {
			assert.Panics(t, func() { setupScannerV4Integration(ctx, s, iis) })
		}
	})

	t.Run("do not try upsert if default integration exists with correct categories", func(t *testing.T) {
		testutils.MustUpdateFeature(t, features.ScannerV4, true)
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		// Return an integration with correct categories - no reconciliation needed.
		existingCorrect := &storage.ImageIntegration{
			Id:   defID,
			Name: "Scanner V4",
			Type: scannerTypes.ScannerV4,
			Categories: []storage.ImageIntegrationCategory{
				storage.ImageIntegrationCategory_SCANNER,
				storage.ImageIntegrationCategory_NODE_SCANNER,
			},
			IntegrationConfig: &storage.ImageIntegration_ScannerV4{
				ScannerV4: &storage.ScannerV4Config{},
			},
		}
		s.EXPECT().Get(ctx, defID).Return(existingCorrect, true, nil)
		s.EXPECT().PruneMany(ctx, []string{"ID-Other-ScannerV4"})
		setupScannerV4Integration(ctx, s, iis)
	})
}

func TestSetupLegacyScannerIntegration(t *testing.T) {
	ctx := context.Background()

	iis := []*storage.ImageIntegration{
		{Id: "ID-ScannerV4", Type: scannerTypes.ScannerV4},
		{Id: "ID-Clairify-1", Type: scannerTypes.Clairify},
		{Id: "ID-Clairify-2", Type: scannerTypes.Clairify},
	}

	t.Run("do nothing when LegacyScanner is enabled", func(t *testing.T) {
		testutils.MustUpdateFeature(t, features.LegacyScanner, true)
		ctrl := gomock.NewController(t)
		s := mockIIStore.NewMockStore(ctrl)
		h := mockHealthDS.NewMockDataStore(ctrl)

		setupLegacyScannerIntegration(ctx, s, h, iis)
	})

	t.Run("do nothing if no Clairify integrations", func(t *testing.T) {
		testutils.MustUpdateFeature(t, features.LegacyScanner, false)
		ctrl := gomock.NewController(t)
		s := mockIIStore.NewMockStore(ctrl)
		h := mockHealthDS.NewMockDataStore(ctrl)

		setupLegacyScannerIntegration(ctx, s, h, iis[:1])
	})

	t.Run("delete Clairify integrations and health when feature disabled", func(t *testing.T) {
		testutils.MustUpdateFeature(t, features.LegacyScanner, false)
		ctrl := gomock.NewController(t)
		s := mockIIStore.NewMockStore(ctrl)
		h := mockHealthDS.NewMockDataStore(ctrl)

		s.EXPECT().PruneMany(ctx, []string{"ID-Clairify-1", "ID-Clairify-2"})
		h.EXPECT().RemoveIntegrationHealth(ctx, "ID-Clairify-1").Return(nil)
		h.EXPECT().RemoveIntegrationHealth(ctx, "ID-Clairify-2").Return(nil)

		setupLegacyScannerIntegration(ctx, s, h, iis)
	})

	t.Run("ignore NotFound when health record does not exist", func(t *testing.T) {
		testutils.MustUpdateFeature(t, features.LegacyScanner, false)
		ctrl := gomock.NewController(t)
		s := mockIIStore.NewMockStore(ctrl)
		h := mockHealthDS.NewMockDataStore(ctrl)

		s.EXPECT().PruneMany(ctx, []string{"ID-Clairify-1", "ID-Clairify-2"})
		h.EXPECT().RemoveIntegrationHealth(ctx, "ID-Clairify-1").Return(errox.NotFound.New("not found"))
		h.EXPECT().RemoveIntegrationHealth(ctx, "ID-Clairify-2").Return(nil)

		setupLegacyScannerIntegration(ctx, s, h, iis)
	})
}

func TestCreateDefaultScannerV4Integration(t *testing.T) {
	ctx := context.Background()
	defaultID := store.DefaultScannerV4Integration.GetId()

	t.Run("create default integration when it does not exist", func(t *testing.T) {
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		s.EXPECT().Get(ctx, defaultID).Return(nil, false, nil)
		s.EXPECT().Upsert(ctx, store.DefaultScannerV4Integration).Return(nil)

		createDefaultScannerV4Integration(ctx, s)
	})

	t.Run("reconcile categories when existing integration has SCANNER only", func(t *testing.T) {
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		// Existing integration with SCANNER category only (old default before node scanning).
		existingScannerOnly := &storage.ImageIntegration{
			Id:   defaultID,
			Name: "Scanner V4",
			Type: scannerTypes.ScannerV4,
			Categories: []storage.ImageIntegrationCategory{
				storage.ImageIntegrationCategory_SCANNER,
			},
			IntegrationConfig: &storage.ImageIntegration_ScannerV4{
				ScannerV4: &storage.ScannerV4Config{
					IndexerEndpoint: "custom-indexer:8443",
					MatcherEndpoint: "custom-matcher:8443",
				},
			},
		}

		s.EXPECT().Get(ctx, defaultID).Return(existingScannerOnly, true, nil)
		s.EXPECT().Upsert(ctx, gomock.Any()).DoAndReturn(func(_ context.Context, ii *storage.ImageIntegration) error {
			// Verify categories were reconciled to include NODE_SCANNER.
			assert.ElementsMatch(t, store.DefaultScannerV4Integration.GetCategories(), ii.GetCategories())
			// Verify other fields were preserved (not wholesale replaced).
			assert.Equal(t, "custom-indexer:8443", ii.GetScannerV4().GetIndexerEndpoint())
			assert.Equal(t, "custom-matcher:8443", ii.GetScannerV4().GetMatcherEndpoint())
			return nil
		})

		createDefaultScannerV4Integration(ctx, s)
	})

	t.Run("reconcile categories when existing integration has wrong categories", func(t *testing.T) {
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		// Existing integration with only NODE_SCANNER (edge case).
		existingNodeOnly := &storage.ImageIntegration{
			Id:   defaultID,
			Name: "Scanner V4",
			Type: scannerTypes.ScannerV4,
			Categories: []storage.ImageIntegrationCategory{
				storage.ImageIntegrationCategory_NODE_SCANNER,
			},
			IntegrationConfig: &storage.ImageIntegration_ScannerV4{
				ScannerV4: &storage.ScannerV4Config{
					IndexerEndpoint: "indexer:8080",
					MatcherEndpoint: "matcher:8080",
				},
			},
		}

		s.EXPECT().Get(ctx, defaultID).Return(existingNodeOnly, true, nil)
		s.EXPECT().Upsert(ctx, gomock.Any()).DoAndReturn(func(_ context.Context, ii *storage.ImageIntegration) error {
			assert.ElementsMatch(t, store.DefaultScannerV4Integration.GetCategories(), ii.GetCategories())
			assert.Equal(t, "indexer:8080", ii.GetScannerV4().GetIndexerEndpoint())
			return nil
		})

		createDefaultScannerV4Integration(ctx, s)
	})

	t.Run("reconcile categories when existing integration has nil categories", func(t *testing.T) {
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		// Ancient default shape: stored integration with no categories at all.
		existingNilCategories := &storage.ImageIntegration{
			Id:         defaultID,
			Name:       "Scanner V4",
			Type:       scannerTypes.ScannerV4,
			Categories: nil,
			IntegrationConfig: &storage.ImageIntegration_ScannerV4{
				ScannerV4: &storage.ScannerV4Config{
					IndexerEndpoint: "legacy-indexer:8443",
				},
			},
		}

		s.EXPECT().Get(ctx, defaultID).Return(existingNilCategories, true, nil)
		s.EXPECT().Upsert(ctx, gomock.Any()).DoAndReturn(func(_ context.Context, ii *storage.ImageIntegration) error {
			assert.ElementsMatch(t, store.DefaultScannerV4Integration.GetCategories(), ii.GetCategories())
			assert.Equal(t, "legacy-indexer:8443", ii.GetScannerV4().GetIndexerEndpoint())
			return nil
		})

		createDefaultScannerV4Integration(ctx, s)
	})

	t.Run("do nothing when existing integration already has correct categories", func(t *testing.T) {
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		// Existing integration with correct categories.
		existingCorrect := &storage.ImageIntegration{
			Id:   defaultID,
			Name: "Scanner V4",
			Type: scannerTypes.ScannerV4,
			Categories: []storage.ImageIntegrationCategory{
				storage.ImageIntegrationCategory_SCANNER,
				storage.ImageIntegrationCategory_NODE_SCANNER,
			},
			IntegrationConfig: &storage.ImageIntegration_ScannerV4{
				ScannerV4: &storage.ScannerV4Config{},
			},
		}

		s.EXPECT().Get(ctx, defaultID).Return(existingCorrect, true, nil)
		// No Upsert expected when categories are already correct.

		createDefaultScannerV4Integration(ctx, s)
	})

	t.Run("do nothing when Get returns error", func(t *testing.T) {
		s := mockIIStore.NewMockStore(gomock.NewController(t))

		s.EXPECT().Get(ctx, defaultID).Return(nil, false, errors.New("database error"))
		// No Upsert expected when Get fails.

		if buildinfo.ReleaseBuild {
			createDefaultScannerV4Integration(ctx, s)
		} else {
			assert.Panics(t, func() { createDefaultScannerV4Integration(ctx, s) })
		}
	})
}

func TestCategoriesMatch(t *testing.T) {
	testCases := []struct {
		name     string
		a        []storage.ImageIntegrationCategory
		b        []storage.ImageIntegrationCategory
		expected bool
	}{
		{
			"empty slices match",
			[]storage.ImageIntegrationCategory{},
			[]storage.ImageIntegrationCategory{},
			true,
		},
		{
			"nil and empty slice match",
			nil,
			[]storage.ImageIntegrationCategory{},
			true,
		},
		{
			"same single element",
			[]storage.ImageIntegrationCategory{storage.ImageIntegrationCategory_SCANNER},
			[]storage.ImageIntegrationCategory{storage.ImageIntegrationCategory_SCANNER},
			true,
		},
		{
			"same multiple elements in same order",
			[]storage.ImageIntegrationCategory{
				storage.ImageIntegrationCategory_SCANNER,
				storage.ImageIntegrationCategory_NODE_SCANNER,
			},
			[]storage.ImageIntegrationCategory{
				storage.ImageIntegrationCategory_SCANNER,
				storage.ImageIntegrationCategory_NODE_SCANNER,
			},
			true,
		},
		{
			"same multiple elements in different order",
			[]storage.ImageIntegrationCategory{
				storage.ImageIntegrationCategory_NODE_SCANNER,
				storage.ImageIntegrationCategory_SCANNER,
			},
			[]storage.ImageIntegrationCategory{
				storage.ImageIntegrationCategory_SCANNER,
				storage.ImageIntegrationCategory_NODE_SCANNER,
			},
			true,
		},
		{
			"different lengths do not match",
			[]storage.ImageIntegrationCategory{storage.ImageIntegrationCategory_SCANNER},
			[]storage.ImageIntegrationCategory{
				storage.ImageIntegrationCategory_SCANNER,
				storage.ImageIntegrationCategory_NODE_SCANNER,
			},
			false,
		},
		{
			"different elements do not match",
			[]storage.ImageIntegrationCategory{storage.ImageIntegrationCategory_SCANNER},
			[]storage.ImageIntegrationCategory{storage.ImageIntegrationCategory_NODE_SCANNER},
			false,
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			result := categoriesMatch(tc.a, tc.b)
			assert.Equal(t, tc.expected, result)
		})
	}
}
