#!/usr/bin/env bash
set -eoux pipefail

# This script creates and enables a test policy that triggers on file activity events from berserker
# The policy will trigger on file access in /tmp/data which is where berserker generates file activity

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd)"

# Create a file activity policy that matches the directory used by berserker
# Berserker generates file activity in /tmp/data (defined in berserker workload files)
POLICY_JSON='{
  "name": "Berserker File Activity Test Policy",
  "description": "Test policy for berserker file activity performance testing - triggers on file access in /tmp/data",
  "rationale": "This policy matches file activity generated by berserker workload to measure performance impact",
  "remediation": "This is a test policy for performance testing with berserker",
  "categories": ["Anomalous Activity"],
  "lifecycleStages": ["RUNTIME"],
  "eventSource": "DEPLOYMENT_EVENT",
  "severity": "LOW_SEVERITY",
  "disabled": false,
  "policySections": [
    {
      "policyGroups": [
        {
          "fieldName": "File Path",
          "values": [
            {
              "value": "/tmp/data/.*"
            }
          ]
        }
      ]
    }
  ],
  "mitreAttackVectors": [],
  "isDefault": false
}'

# Post the policy to Central
curl -k -X POST \
  -H "Authorization: Bearer ${ROX_API_TOKEN}" \
  -H "Content-Type: application/json" \
  -d "${POLICY_JSON}" \
  "${ROX_ENDPOINT}/v1/policies" || echo "Policy may already exist or failed to create"

echo "Berserker file activity test policy enabled"
