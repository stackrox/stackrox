enable_console_plugin() {
    info "Enabling advanced-cluster-security console plugin"

    # Wait for the ConsolePlugin CRD and resource to exist
    info "Waiting for ConsolePlugin CRD to be established"
    kubectl wait --for=condition=Established --timeout=120s \
        crd/consoleplugins.console.openshift.io

    info "Waiting for advanced-cluster-security ConsolePlugin resource to be created"
    kubectl wait --for=create --timeout=120s \
        consoleplugin/advanced-cluster-security

    # Enable the plugin in the console operator config (idempotent)
    local current_plugins
    current_plugins=$(oc get console.operator.openshift.io cluster -o jsonpath='{.spec.plugins[*]}' 2>/dev/null || echo "")
    if [[ "$current_plugins" =~ (^|[[:space:]])advanced-cluster-security([[:space:]]|$) ]]; then
        info "Plugin 'advanced-cluster-security' is already enabled"
    else
        info "Enabling plugin 'advanced-cluster-security' in console config"
        if [[ -z "$current_plugins" || "$current_plugins" == "null" ]]; then
            # No plugins enabled yet, initialize the array
            oc patch console.operator.openshift.io cluster --type=merge \
              -p '{"spec":{"plugins":["advanced-cluster-security"]}}'
        else
            # Append to existing plugins
            oc patch console.operator.openshift.io cluster --type=json \
              -p '[{"op": "add", "path": "/spec/plugins/-", "value": "advanced-cluster-security"}]'
        fi

        # Wait for console deployment to roll out with plugin configuration
        info "Waiting for console deployment to roll out with plugin enabled"
        kubectl rollout status deployment/console -n openshift-console --timeout=3m || {
            die "Console rollout did not complete within 3m after enabling plugin"
        }
    fi
}

# Ensure the roxie CLI is installed and on PATH. run-ui-e2e.sh runs under OpenShift CI
# (Prow), where the GHA roxie/install-cli action is unavailable, so we rely on the
# self-installing scripts/roxie.sh wrapper, which downloads the version pinned in
# ROXIE_VERSION into bin/<os>_<arch>/roxie.
ensure_roxie_on_path() {
    local os arch
    case "$(uname -s)" in
        Linux*) os="linux" ;;
        Darwin*) os="darwin" ;;
        *) die "Unsupported operating system: $(uname -s)" ;;
    esac
    case "$(uname -m)" in
        x86_64) arch="amd64" ;;
        arm64|aarch64) arch="arm64" ;;
        *) die "Unsupported architecture: $(uname -m)" ;;
    esac

    # Triggers the download/install of the pinned roxie version if it is not present yet.
    "$ROOT/scripts/roxie.sh" version
    export PATH="$ROOT/bin/${os}_${arch}:$PATH"

    check_for_roxie
}

# TEMPORARY (ROX-36577): capture why deployed images are not scanned under the roxie deploy.
# Strictly read-only and best-effort — every command is guarded so it can never fail the job.
# Remove once the image-scanning issue is understood and fixed.
dump_scanning_diagnostics() {
    local label="${1:-diag}"
    local out="${ARTIFACT_DIR:-/tmp}/scanning-diagnostics/${label}"
    mkdir -p "$out"
    info "════════ SCANNING DIAGNOSTICS [${label}] (temporary, ROX-36577) ════════"

    retrying_kubectl -n stackrox get secrets </dev/null > "$out/secrets.txt" 2>&1 || true
    retrying_kubectl -n stackrox get central,securedcluster -o yaml </dev/null > "$out/crs.yaml" 2>&1 || true
    retrying_kubectl -n stackrox get deploy central sensor -o yaml </dev/null > "$out/deployments.yaml" 2>&1 || true
    retrying_kubectl -n stackrox get deploy,ds,pods -o wide </dev/null > "$out/workloads.txt" 2>&1 || true
    retrying_kubectl -n stackrox logs deploy/central --tail=3000 </dev/null > "$out/central.log" 2>&1 || true
    retrying_kubectl -n stackrox logs deploy/sensor --tail=3000 </dev/null > "$out/sensor.log" 2>&1 || true

    local api="${API_ENDPOINT:-localhost:${LOCAL_PORT:-443}}"
    curl -sk --max-time 30 -u "admin:${ROX_ADMIN_PASSWORD:-}" \
        "https://${api}/v1/imageintegrations" > "$out/imageintegrations.json" 2>/dev/null || true
    curl -sk --max-time 90 -u "admin:${ROX_ADMIN_PASSWORD:-}" \
        "https://${api}/v1/images?pagination.limit=500" > "$out/images.json" 2>/dev/null || true

    info "--- image integrations (name / type / autogenerated) ---"
    jq -r '.integrations[]? | "  \(.name)\t\(.type)\tautogen=\(.autogenerated)\tcats=\((.categories // [])|join(","))"' \
        "$out/imageintegrations.json" 2>/dev/null || info "  (could not parse imageintegrations.json)"
    local total scanned
    total="$(jq -r '.images | length' "$out/images.json" 2>/dev/null || echo '?')"
    scanned="$(jq -r '[.images[]? | select((.components // 0) > 0)] | length' "$out/images.json" 2>/dev/null || echo '?')"
    info "--- images: total=${total} with_components=${scanned} ---"
    jq -r '.images[]? | "  \(.name.fullName)\tcomponents=\(.components // "nil")\tnotes=\((.notes // [])|join(","))"' \
        "$out/images.json" 2>/dev/null | head -30 || true
    info "--- central/sensor deploy imagePullSecrets ---"
    grep -niA3 "imagePullSecrets" "$out/deployments.yaml" 2>/dev/null | head -30 || info "  (none found)"
    info "--- central log: registry/integration/scan/enrich/quay ---"
    grep -iE "registr|integration|scan|enrich|quay|pull.?secret" "$out/central.log" 2>/dev/null | tail -80 || info "  (no matches / no log)"
    info "--- sensor log: secret/integration/dockercfg/autogen ---"
    grep -iE "secret|integration|registr|dockercfg|dockerconfig|autogen" "$out/sensor.log" 2>/dev/null | tail -80 || info "  (no matches / no log)"
    info "════════ END SCANNING DIAGNOSTICS [${label}] ════════"
}

test_ui_e2e() {
    info "Starting UI e2e tests"

    require_environment "ORCHESTRATOR_FLAVOR"
    require_environment "KUBECONFIG"

    export DEPLOY_DIR="deploy/${ORCHESTRATOR_FLAVOR}"

    export_test_environment

    # The UI e2e Cypress specs (e.g. policies/policyCreateWorkflow) target the drag-and-drop
    # policy criteria UI, which Central renders only when ROX_POLICY_CRITERIA_MODAL is disabled.
    # The helm-based deploy this suite used never enabled the flag, but the roxie compat layer's
    # collect_feature_flags() turns it on by default. Force it off here to preserve the
    # pre-migration behavior the tests expect.
    export ROX_POLICY_CRITERIA_MODAL=false

    setup_deployment_env false false
    remove_existing_stackrox_resources
    setup_default_TLS_certs

    # deploy the optional components before stackrox
    deploy_optional_e2e_components

    # Deploy StackRox with roxie (operator-based) instead of helm. The compat layer
    # translates this suite's environment-variable based configuration into a roxie
    # configuration. deploy/roxie-config.yaml pauses operator reconciliation so the tests
    # run against a stable deployment.
    ensure_roxie_on_path
    local roxie_config; roxie_config="$(mktemp)"
    merge_yaml "$roxie_config" < "$ROOT/deploy/roxie-config.yaml"
    # resourceProfile: ci scales resource requests down to CI size. Without it, roxie deploys
    # with production-sized requests, which do not fit on the small CI clusters (e.g. the
    # 3-node GKE ui-e2e cluster), leaving central-db unschedulable and Central crash-looping
    # until the deploy timeout. This can only be set via config or the --resources flag.
    merge_yaml "$roxie_config" <<'EOF'
central:
  resourceProfile: ci
securedCluster:
  resourceProfile: ci
EOF
    # Scanner V4's matcher must finish loading its vulnerability store before it can scan
    # images. Loading every vuln source takes far longer than the test window, so the matcher
    # stays "not initialized" and every image reports 0 components, leaving the vuln-management
    # Cypress specs asserting on empty tables. Limit the sources to the CI allowlist (matching
    # the helm/operator path in tests/e2e/lib.sh) so the initial load finishes quickly. The env
    # var goes on the Central CR's customize.envVars, which the operator propagates to the
    # scanner-v4-matcher deployment.
    if [[ -n "${SCANNER_V4_CI_VULN_BUNDLE_ALLOWLIST:-}" ]]; then
        set_custom_env "$roxie_config" "central" \
            "SCANNER_V4_MATCHER_VULN_BUNDLE_ALLOWLIST" "$SCANNER_V4_CI_VULN_BUNDLE_ALLOWLIST"
    fi
    # Make the scanner-v4-matcher report NotReady until its vulnerability store has finished
    # loading, so the roxie deploy (--central-wait) blocks until scanning actually works before
    # the tests run. The allowlist above bounds the load time to well under that wait. The
    # helm/operator path does this whenever SCANNER_V4_VULN_READINESS is set (true by default
    # via export_test_environment, tests/e2e/lib.sh); the roxie compat layer does not translate
    # it, so without this the matcher is Ready immediately, the deploy returns, and the
    # vuln-management specs run against still-unscanned images.
    if [[ "${SCANNER_V4_VULN_READINESS:-false}" == "true" ]]; then
        set_custom_env "$roxie_config" "central" "SCANNER_V4_MATCHER_READINESS" "vulnerability"
        # Under the ci resource profile the matcher gets a single CPU, so loading the (allowlisted)
        # vulnerability bundles is slow. Give the roxie deploy enough time to wait for it, matching
        # the helm path's 1h scanner-v4 vuln-readiness wait; the default 40m is too short.
        export ROXIE_CENTRAL_WAIT="${ROXIE_CENTRAL_WAIT:-70m}"
        export ROXIE_SECURED_CLUSTER_WAIT="${ROXIE_SECURED_CLUSTER_WAIT:-70m}"
    fi
    deploy_stackrox_with_roxie_compat "$roxie_config"
    rm -f "$roxie_config"

    # TEMPORARY (ROX-36577): snapshot scanning state right after deploy.
    dump_scanning_diagnostics after-deploy

    # Enable the console plugin for OpenShift if the ConsolePlugin resource exists
    if [[ "${ORCHESTRATOR_FLAVOR}" == "openshift" ]] && kubectl get consoleplugin advanced-cluster-security &>/dev/null; then
        enable_console_plugin
    fi

    run_ui_e2e_tests
}

run_ui_e2e_tests() {
    info "Running UI e2e tests"

    if [[ "${LOAD_BALANCER}" == "lb" ]]; then
        local hostname
        if [[ "${API_HOSTNAME}" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
            info "Getting hostname from IP: ${API_HOSTNAME}"
            hostname=$("$ROOT/tests/e2e/get_hostname.py" "${API_HOSTNAME}")
        else
            hostname="${API_HOSTNAME}"
        fi
        info "Hostname for central-lb alias: ${hostname}"
        echo "central-lb ${hostname}" > /tmp/hostaliases
        export HOSTALIASES=/tmp/hostaliases
        export UI_BASE_URL="https://central-lb:443"
    elif [[ "${LOAD_BALANCER}" == "route" ]]; then
        die "unsupported LOAD_BALANCER ${LOAD_BALANCER}"
    else
        export UI_BASE_URL="https://localhost:${LOCAL_PORT}"
    fi

    make -C ui test-e2e || touch FAIL

    store_test_results "ui/test-results/reports/cypress/integration/." "cy-reps"
    # OCP console plugin tests write to a separate directory; only present on OpenShift runs
    if [[ -d "ui/test-results/reports/cypress/integration-ocp" ]]; then
        store_test_results "ui/test-results/reports/cypress/integration-ocp/." "cy-reps/consolePlugin"
    fi

    if is_OPENSHIFT_CI; then
        cp -a ui/test-results/artifacts/* "${ARTIFACT_DIR}/" || true
    fi

    # TEMPORARY (ROX-36577): snapshot scanning state after the suite ran, so scan data has
    # had the full test window to settle. Runs whether or not the suite passed.
    dump_scanning_diagnostics after-tests

    [[ ! -f FAIL ]] || die "UI e2e tests failed"
}

test_ui_e2e
