#!/usr/bin/env bash
# Regenerates the parts of this shim that are copies of upstream OpenShift
# operator files, from pinned upstream commits (never floats on a branch):
#   - sccs.yaml    -- entirely upstream, verbatim concatenation of two files.
#   - objects.yaml -- only two fields are upstream, spliced in place; the rest
#     of the file (namespaces, singleton CRs, the other two ConfigMaps, the
#     no-op DaemonSet, ...) is first-party and untouched:
#       * openshift-kube-apiserver/config ConfigMap's apiServerArguments
#       * openshift-kube-controller-manager/config ConfigMap's extendedArguments
#
# Run it directly to re-sync against the pins below. To bump the pins, edit
# KAS_OPERATOR_SHA/KCM_OPERATOR_SHA then re-run -- or let
# .github/workflows/update_openshift_platform_shim_periodic.yaml do both
# automatically (see README.md).
#
# Requires: curl, python3 + PyYAML (check: `python3 -c 'import yaml'`; install
# with `python3 -m pip install pyyaml` if missing). PyYAML, not yq, because:
# (a) it's a pure-Python library, not a new CLI binary to fetch/pin/trust on
# top of this repo's existing toolchain (kind/kubectl/helm/docker/jq/openssl/
# curl/go); (b) python3 is already used elsewhere in this repo's CI tooling;
# (c) unlike a hand-rolled regex/text splice of upstream's YAML, it round-trips
# the parsed mapping's key order losslessly, which matters here: objects.yaml's
# JSON blobs preserve upstream's authored key order (not alphabetical), and a
# byte-exact re-splice when nothing changed upstream is how this script's
# output gets sanity-checked (`git diff` should be empty between syncs).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OBJECTS_YAML="$SCRIPT_DIR/objects.yaml"
SCCS_YAML="$SCRIPT_DIR/sccs.yaml"

# Pinned upstream commits (both repos' default branch is "main", NOT "master":
# the README this script replaces had master-branch curl commands, which still
# happen to resolve today because GitHub keeps a redirect after a repo's
# default-branch rename, but that's not something to build a pin on).
KAS_OPERATOR_SHA=5105250647f33a232b1bf2982372f7cc66580deb  # cluster-kube-apiserver-operator@main HEAD as of 2026-11-06
KCM_OPERATOR_SHA=cd45079d8bb7a391ba0eb3282d9ef75232fe425c  # cluster-kube-controller-manager-operator@main HEAD as of 2026-11-06

KAS_RAW="https://raw.githubusercontent.com/openshift/cluster-kube-apiserver-operator/${KAS_OPERATOR_SHA}"
KCM_RAW="https://raw.githubusercontent.com/openshift/cluster-kube-controller-manager-operator/${KCM_OPERATOR_SHA}"

log() { printf '>> %s\n' "$*" >&2; }

python3 -c 'import yaml' 2>/dev/null \
  || { echo "regenerate.sh: missing PyYAML -- run 'python3 -m pip install pyyaml' first" >&2; exit 1; }

tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT

# --- sccs.yaml: verbatim concatenation of the two real SCC manifests --------
log "fetching SCCs from cluster-kube-apiserver-operator@${KAS_OPERATOR_SHA}"
restricted="$(curl -fsSL "${KAS_RAW}/bindata/bootkube/scc-manifests/0000_20_kube-apiserver-operator_00_scc-restricted-v2.yaml")"
privileged="$(curl -fsSL "${KAS_RAW}/bindata/bootkube/scc-manifests/0000_20_kube-apiserver-operator_00_scc-privileged.yaml")"

# The explanatory header below (the kubectl create vs apply gotcha) is
# hand-authored, not upstream; kept as a literal constant here, instead of
# re-extracted from the previous sccs.yaml, so it survives even if sccs.yaml
# is ever deleted or corrupted.
{
  cat <<HEADER
# Real SCCs (verbatim from cluster-kube-apiserver-operator's bootkube bindata,
# the manifests OpenShift itself installs). Applied via \`kubectl create\`, NOT
# \`kubectl apply\`: the real SecurityContextConstraints CRD requires priority,
# allowedCapabilities, defaultAddCapabilities, and volumes to be PRESENT even
# when null, but \`kubectl apply\`'s client-side JSON-merge machinery strips
# explicit \`key: null\` fields before sending the request, which then fails CRD
# validation ("missing required field"). A plain create (or \`apply
# --server-side\`) sends the object as-is, nulls included.
#
# Regenerated by regenerate.sh -- do not hand-edit. Source:
# cluster-kube-apiserver-operator@${KAS_OPERATOR_SHA}
#   bindata/bootkube/scc-manifests/0000_20_kube-apiserver-operator_00_scc-restricted-v2.yaml
#   bindata/bootkube/scc-manifests/0000_20_kube-apiserver-operator_00_scc-privileged.yaml
HEADER
  printf '%s\n' "$restricted"
  printf -- '---\n'
  printf '%s\n' "$privileged"
} >"$SCCS_YAML"
log "wrote $SCCS_YAML"

# --- objects.yaml: splice apiServerArguments / extendedArguments -----------
log "fetching defaultconfig.yaml from both operators"
curl -fsSL -o "$tmpdir/kas-defaultconfig.yaml" "${KAS_RAW}/bindata/assets/config/defaultconfig.yaml"
curl -fsSL -o "$tmpdir/kcm-defaultconfig.yaml" "${KCM_RAW}/bindata/assets/config/defaultconfig.yaml"

# objects.yaml is otherwise first-party: rewrite only the two upstream fields,
# anchored on "# BEGIN/END UPSTREAM" marker comments that live just outside the
# JSON blob (they can't live inside it: that's a literal block scalar parsed
# downstream as JSON, so a "#" in there would corrupt the ConfigMap's data
# instead of commenting anything out). A plain-text splice of the one targeted
# key inside that one-line JSON blob would still need to hand-balance nested
# braces/arrays; parsing the line as JSON, replacing one key, and re-dumping is
# simpler and exact, and leaves every other byte on that line untouched.
KAS_OPERATOR_SHA="$KAS_OPERATOR_SHA" KCM_OPERATOR_SHA="$KCM_OPERATOR_SHA" \
OBJECTS_YAML="$OBJECTS_YAML" \
KAS_DEFAULTCONFIG_FILE="$tmpdir/kas-defaultconfig.yaml" KCM_DEFAULTCONFIG_FILE="$tmpdir/kcm-defaultconfig.yaml" \
python3 - <<'PYEOF'
import json
import os
import sys

import yaml

objects_path = os.environ["OBJECTS_YAML"]
with open(objects_path) as f:
    lines = f.readlines()

with open(os.environ["KAS_DEFAULTCONFIG_FILE"]) as f:
    kas_defaultconfig = f.read()
with open(os.environ["KCM_DEFAULTCONFIG_FILE"]) as f:
    kcm_defaultconfig = f.read()

SPECS = [
    {
        "repo": "cluster-kube-apiserver-operator",
        "sha": os.environ["KAS_OPERATOR_SHA"],
        "source_path": "bindata/assets/config/defaultconfig.yaml",
        "field": "apiServerArguments",
        "upstream_yaml": kas_defaultconfig,
    },
    {
        "repo": "cluster-kube-controller-manager-operator",
        "sha": os.environ["KCM_OPERATOR_SHA"],
        "source_path": "bindata/assets/config/defaultconfig.yaml",
        "field": "extendedArguments",
        "upstream_yaml": kcm_defaultconfig,
    },
]


def jsonify(value):
    """Coerce a PyYAML-parsed scalar to what the real apiServerArguments/
    extendedArguments map[string][]string type (and this file's existing
    content) uses: plain strings, lowercase for bools."""
    if isinstance(value, bool):
        return str(value).lower()
    return str(value)


for spec in SPECS:
    begin_idx = next(
        (
            i
            for i, l in enumerate(lines)
            if l.lstrip().startswith("# BEGIN UPSTREAM:")
            and spec["repo"] in l
            and f'({spec["field"]})' in l
        ),
        None,
    )
    if begin_idx is None:
        sys.exit(f'regenerate.sh: no BEGIN UPSTREAM marker found for {spec["repo"]} ({spec["field"]}) in {objects_path}')
    end_idx = next(
        (i for i in range(begin_idx + 1, len(lines)) if lines[i].lstrip().startswith("# END UPSTREAM")),
        None,
    )
    if end_idx is None:
        sys.exit(f"regenerate.sh: no matching END UPSTREAM marker after line {begin_idx + 1} in {objects_path}")

    json_idx = next(
        (i for i in range(begin_idx + 1, end_idx) if lines[i].strip().startswith("{")),
        None,
    )
    if json_idx is None:
        sys.exit(f"regenerate.sh: no JSON content line between the UPSTREAM markers at lines {begin_idx + 1}-{end_idx + 1}")

    raw = lines[json_idx]
    indent = raw[: len(raw) - len(raw.lstrip())]
    obj = json.loads(raw.strip())
    if spec["field"] not in obj:
        sys.exit(f'regenerate.sh: key "{spec["field"]}" not found in the JSON blob at line {json_idx + 1}')

    upstream = yaml.safe_load(spec["upstream_yaml"])
    if spec["field"] not in upstream:
        sys.exit(
            f'regenerate.sh: key "{spec["field"]}" not found in upstream {spec["source_path"]} '
            f'({spec["repo"]}@{spec["sha"]}) -- has the upstream schema changed?'
        )

    # Re-assigning an EXISTING dict key in Python keeps its original position,
    # so apiServerArguments/extendedArguments stays exactly where it already
    # was among its first-party sibling keys (admission, apiVersion, ...).
    obj[spec["field"]] = {k: [jsonify(x) for x in v] for k, v in upstream[spec["field"]].items()}

    # Match this blob's own existing separator style (some of this file's
    # ConfigMaps use Go/jq-compact JSON, others use spaced JSON) so unrelated
    # keys on the same line stay byte-identical when their values don't change.
    spaced = '": "' in raw[:80]
    separators = (", ", ": ") if spaced else (",", ":")
    lines[json_idx] = indent + json.dumps(obj, separators=separators) + "\n"

    begin_indent = lines[begin_idx][: len(lines[begin_idx]) - len(lines[begin_idx].lstrip())]
    lines[begin_idx] = f'{begin_indent}# BEGIN UPSTREAM: {spec["repo"]}@{spec["sha"]} {spec["source_path"]} ({spec["field"]})\n'

with open(objects_path, "w") as f:
    f.writelines(lines)
PYEOF
log "wrote $OBJECTS_YAML"
